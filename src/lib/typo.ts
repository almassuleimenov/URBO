/**
 * Русская экранная типографика:
 * — короткие предлоги, союзы и частицы не висят в конце строки (неразрывный пробел после них);
 * — тире не начинает строку (неразрывный пробел перед ним);
 * — числа не отрываются от единиц и знака ₸.
 */
const NBSP = " ";
const SHORT =
  /(^|[\s(«"])(а|в|во|и|к|ко|с|со|у|о|об|от|до|на|не|ни|но|по|за|из|для|без|при|над|под|про|как|что|или|же|ли|бы|мы|вы|он|её|их|это|так|уже)\s+/giu;

export function typo(text: string): string {
  return text
    .replace(SHORT, (_, pre: string, word: string) => `${pre}${word}${NBSP}`)
    .replace(SHORT, (_, pre: string, word: string) => `${pre}${word}${NBSP}`) // второй проход для «и в»
    .replace(/\s+—/g, `${NBSP}—`)
    .replace(/(\d)\s+(₸|км|м|мин|сек|тыс\.)/g, `$1${NBSP}$2`);
}
